"""Build migrations/015-directory-seed.sql from the two research outputs.

    python3 directory_seed.py [LUCKNOW_FINAL_JSON] [NCR_FINAL_JSON]

Defaults read /home/suhel/data/final.json (Lucknow ranked list) and
/home/suhel/data_ncr/final.json (Noida / Greater Noida / Delhi list).

The output is an upsert, so re-running it (deploy.mjs --migrate re-applies every
migration) refreshes contact details without touching anyone's status or note,
which live on directory_progress. Rows that dropped out of a list are deleted.
"""
import json, re, sys

LKO = sys.argv[1] if len(sys.argv) > 1 else "/home/suhel/data/final.json"
NCR = sys.argv[2] if len(sys.argv) > 2 else "/home/suhel/data_ncr/final.json"
OUT = "migrations/015-directory-seed.sql"
STATUS = {"Verified": "V", "From my PDF": "PDF", "Found elsewhere": "Dir"}
COLS = ["id", "region", "city", "sort", "rank", "name", "area", "address", "kind", "size", "tier", "score",
        "rating", "stack", "mern", "hiring", "hiring_label", "job_title", "job_url", "emails", "phones",
        "careers_url", "website", "linkedin", "contact_status", "warning", "notes", "checked"]

def slug(s):
    s = re.sub(r"\(.*?\)", "", s.lower())
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")[:60] or "company"

def url(u):
    """Just the link: some research rows carry a remark after it ("... (no city filter)")."""
    m = re.match(r"https?://[^\s,;)]+", (u or "").strip())
    return m.group(0) if m else ""

def emails(r):
    return [{"e": e["email"], "t": "hr" if e.get("type") == "HR/Careers" else "gen", "s": STATUS.get(e.get("status"), "Dir")}
            for e in r.get("emails") or []][:4]

def phones(r):
    out = []
    for p in r.get("phones") or []:
        n = p.get("number", "")
        out.append({"n": n, "l": p.get("label") or "", "s": STATUS.get(p.get("status"), "Dir"),
                    "m": 1 if re.fullmatch(r"\+91 [6-9]\d{4} \d{5}", n) else 0})
    # HR / WhatsApp lines first, then verified, so the card's first number is the best one to call.
    out.sort(key=lambda p: (p["l"] not in ("HR", "WhatsApp"), p["s"] != "V"))
    return out[:4]

def sql(v):
    if v is None: return "NULL"
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

def lko_rows():
    for i, r in enumerate(json.load(open(LKO))["ranked"]):
        role = (r.get("open_roles") or [{}])[0]
        yield {"region": "lko", "city": "Lucknow", "sort": i, "rank": r["rank"], "name": r["company"],
               "area": r.get("area") or "", "address": r.get("lucknow_address") or "",
               "kind": r.get("company_type") or "", "size": r.get("employees") or "", "tier": r.get("tier") or "",
               "score": r.get("total_score"), "rating": r.get("rating_text") or "",
               "stack": ", ".join(r.get("tech_stack") or []), "mern": r.get("mern_match") or "",
               "hiring": 1 if r.get("fit_role_pts", 0) >= 8 else 0, "hiring_label": r.get("role_grade") or "",
               "job_title": role.get("title") or "", "job_url": url(role.get("url")),
               "emails": emails(r), "phones": phones(r), "careers_url": url(r.get("careers_url")),
               "website": url(r.get("website")), "linkedin": url(r.get("linkedin_url")),
               "contact_status": r.get("contact_status") or "", "warning": r.get("warning") or "",
               "notes": r.get("notes") or "", "checked": r.get("last_checked") or ""}

def ncr_rows():
    for i, r in enumerate(json.load(open(NCR))["rows"]):
        yes = r.get("mern_hiring") == "Yes"
        yield {"region": "ncr", "city": r["city"], "sort": i, "rank": r.get("n"), "name": r["company"],
               "area": r.get("area") or "", "address": r.get("address") or "", "kind": r.get("type") or "",
               "size": r.get("size") or "", "tier": "", "score": None, "rating": "", "stack": "",
               "mern": r.get("mern_hiring") or "", "hiring": 1 if yes else 0,
               "hiring_label": "Hiring MERN (check date)" if yes else "", "job_title": "",
               "job_url": url(r.get("mern_job_url")), "emails": emails(r), "phones": phones(r),
               "careers_url": url(r.get("careers_url")), "website": url(r.get("website")),
               "linkedin": url(r.get("linkedin_url")), "contact_status": r.get("contact_status") or "",
               "warning": "", "notes": r.get("notes") or "", "checked": r.get("last_checked") or ""}

def main():
    lines = ["-- GENERATED by directory_seed.py -- do not edit by hand. Safe to re-run.", ""]
    for region, rows in (("lko", list(lko_rows())), ("ncr", list(ncr_rows()))):
        ids = set()
        for r in rows:
            base = f"{region}:{slug(r['name'])}"
            rid, k = base, 2
            while rid in ids:
                rid, k = f"{base}-{k}", k + 1
            ids.add(rid)
            r["id"] = rid
            r["emails"] = json.dumps(r["emails"], ensure_ascii=False)
            r["phones"] = json.dumps(r["phones"], ensure_ascii=False)
            vals = ",".join(sql(r[c]) for c in COLS)
            upd = ", ".join(f"{c} = excluded.{c}" for c in COLS if c != "id")
            lines.append(f"INSERT INTO directory ({','.join(COLS)}) VALUES ({vals}) ON CONFLICT(id) DO UPDATE SET {upd};")
        lines.append(f"DELETE FROM directory WHERE region = '{region}' AND id NOT IN ({','.join(sql(i) for i in sorted(ids))});")
        print(f"{region}: {len(rows)} rows")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote", OUT)

if __name__ == "__main__":
    main()
